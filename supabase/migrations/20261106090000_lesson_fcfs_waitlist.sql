-- Lesson booking: FCFS queue + waitlist, booking window, per-member limit,
-- cancel cutoff, versioned announcement acknowledgement.
-- Ported from the pea-golf-web prototype (schema.sql) into PEAGC's multi-club schema.

-- ---------- settings (one row per club) ----------
create table if not exists public.lesson_booking_settings (
  club_id uuid primary key references public.clubs(id) on delete cascade,
  booking_open_at timestamptz,
  booking_close_at timestamptz,
  max_bookings_per_member integer not null default 2 check (max_bookings_per_member >= 0),
  cancel_cutoff_hours integer not null default 24 check (cancel_cutoff_hours >= 0),
  announcement_title text not null default '',
  announcement_body text not null default '',
  announcement_version integer not null default 0 check (announcement_version >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users(id),
  check (booking_close_at is null or booking_open_at is null or booking_close_at > booking_open_at)
);

drop trigger if exists set_lesson_booking_settings_updated_at on public.lesson_booking_settings;
create trigger set_lesson_booking_settings_updated_at
before update on public.lesson_booking_settings
for each row execute function public.set_updated_at();

alter table public.lesson_booking_settings enable row level security;
grant select, insert, update on public.lesson_booking_settings to authenticated;
grant all on public.lesson_booking_settings to service_role;

drop policy if exists "lesson_booking_settings_select_club" on public.lesson_booking_settings;
create policy "lesson_booking_settings_select_club"
on public.lesson_booking_settings
for select
to authenticated
using (
  exists (
    select 1 from public.members m
    where m.club_id = lesson_booking_settings.club_id
      and m.user_id = (select auth.uid())
  )
  or exists (
    select 1 from public.user_roles ur
    where ur.club_id = lesson_booking_settings.club_id
      and ur.user_id = (select auth.uid())
  )
);

drop policy if exists "lesson_booking_settings_write_by_admin" on public.lesson_booking_settings;
create policy "lesson_booking_settings_write_by_admin"
on public.lesson_booking_settings
for all
to authenticated
using (
  exists (
    select 1 from public.user_roles ur
    where ur.club_id = lesson_booking_settings.club_id
      and ur.user_id = (select auth.uid())
      and ur.role_key in ('platform_owner', 'club_admin', 'committee')
  )
)
with check (
  exists (
    select 1 from public.user_roles ur
    where ur.club_id = lesson_booking_settings.club_id
      and ur.user_id = (select auth.uid())
      and ur.role_key in ('platform_owner', 'club_admin', 'committee')
  )
);

-- ---------- columns ----------
alter table public.lesson_slots
add column if not exists waitlist_capacity integer not null default 0 check (waitlist_capacity >= 0);

alter table public.lesson_bookings
add column if not exists queue_seq bigint generated by default as identity;

create unique index if not exists lesson_bookings_queue_seq_idx
on public.lesson_bookings (queue_seq);

create index if not exists lesson_bookings_slot_queue_idx
on public.lesson_bookings (slot_id, queue_seq)
where status <> 'cancelled';

alter table public.members
add column if not exists lesson_announcement_ack_version integer not null default 0;

-- Members book only through book_lesson_slot (window, limit, announcement, waitlist rules);
-- the direct-insert policy from the first lesson migration would bypass those rules.
drop policy if exists "lesson_bookings_insert_own_open_slot" on public.lesson_bookings;

-- ---------- capacity trigger now allows the waitlist ----------
create or replace function public.enforce_lesson_slot_capacity()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  slot_limit integer;
  active_count integer;
begin
  if new.status = 'cancelled' then
    return new;
  end if;

  select capacity + waitlist_capacity into slot_limit
  from public.lesson_slots
  where id = new.slot_id
  for update;

  select count(*)::integer into active_count
  from public.lesson_bookings
  where slot_id = new.slot_id
    and status <> 'cancelled'
    and id <> new.id;

  if active_count >= slot_limit then
    raise exception 'lesson_slot_full' using errcode = 'P0001';
  end if;
  return new;
end;
$$;

-- ---------- helpers (not callable by clients) ----------
create or replace function public._lesson_target_match(p_targets text[], p_value text)
returns boolean
language sql
immutable
as $$
  select cardinality(coalesce(p_targets, '{}'::text[])) = 0
      or exists (
        select 1 from unnest(p_targets) t
        where lower(trim(t)) = lower(trim(coalesce(p_value, '')))
      );
$$;

create or replace function public._lesson_slot_start(p_date date, p_time time)
returns timestamptz
language sql
immutable
as $$
  select (p_date + p_time) at time zone 'Asia/Bangkok';
$$;

create or replace function public._lesson_current_member(p_club uuid)
returns public.members
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_member public.members;
begin
  select * into v_member
  from public.members
  where user_id = auth.uid()
    and club_id = p_club
    and archived_at is null
  limit 1;

  if v_member.id is null then
    raise exception 'NOT_MEMBER';
  end if;
  if v_member.status <> 'active' then
    raise exception 'MEMBER_INACTIVE';
  end if;
  return v_member;
end;
$$;

create or replace function public._lesson_settings(p_club uuid)
returns public.lesson_booking_settings
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v public.lesson_booking_settings;
begin
  select * into v from public.lesson_booking_settings where club_id = p_club;
  if v.club_id is null then
    v.club_id := p_club;
    v.max_bookings_per_member := 0;
    v.cancel_cutoff_hours := 0;
    v.announcement_version := 0;
    v.announcement_title := '';
    v.announcement_body := '';
  end if;
  return v;
end;
$$;

-- Shared rule checks for booking into p_slot. p_exclude_booking skips the caller's own
-- booking when it is being moved to another slot.
create or replace function public._lesson_booking_checks(
  p_member public.members,
  p_slot public.lesson_slots,
  p_settings public.lesson_booking_settings,
  p_exclude_booking uuid
)
returns void
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_active integer;
begin
  if p_settings.booking_open_at is null or now() < p_settings.booking_open_at then
    raise exception 'NOT_OPEN';
  end if;
  if p_settings.booking_close_at is not null and now() > p_settings.booking_close_at then
    raise exception 'CLOSED';
  end if;
  if p_settings.announcement_version > 0
     and (p_settings.announcement_title <> '' or p_settings.announcement_body <> '')
     and p_member.lesson_announcement_ack_version < p_settings.announcement_version then
    raise exception 'ANNOUNCEMENT';
  end if;
  if p_slot.id is null or p_slot.archived_at is not null then
    raise exception 'NO_SESSION';
  end if;
  if p_slot.status <> 'open' then
    raise exception 'SESSION_CLOSED';
  end if;
  if not (
    _lesson_target_match(p_slot.target_work_lines, p_member.work_line)
    and _lesson_target_match(p_slot.target_bureaus, p_member.bureau)
    and _lesson_target_match(p_slot.target_divisions, p_member.division)
    and _lesson_target_match(p_slot.target_departments, p_member.department)
    and _lesson_target_match(p_slot.target_sections, p_member.section)
  ) then
    raise exception 'NOT_TARGETED';
  end if;
  if _lesson_slot_start(p_slot.lesson_date, p_slot.start_time) <= now() then
    raise exception 'STARTED';
  end if;
  if exists (
    select 1 from public.lesson_bookings b
    where b.slot_id = p_slot.id
      and b.member_id = p_member.id
      and b.status <> 'cancelled'
      and (p_exclude_booking is null or b.id <> p_exclude_booking)
  ) then
    raise exception 'DUPLICATE';
  end if;
  if p_settings.max_bookings_per_member > 0 then
    select count(*)::integer into v_active
    from public.lesson_bookings b
    join public.lesson_slots s on s.id = b.slot_id
    where b.member_id = p_member.id
      and b.status <> 'cancelled'
      and (p_exclude_booking is null or b.id <> p_exclude_booking)
      and _lesson_slot_start(s.lesson_date, s.start_time) > now();
    if v_active >= p_settings.max_bookings_per_member then
      raise exception 'LIMIT';
    end if;
  end if;
  if exists (
    select 1 from public.lesson_bookings b
    join public.lesson_slots s on s.id = b.slot_id
    where b.member_id = p_member.id
      and b.status <> 'cancelled'
      and (p_exclude_booking is null or b.id <> p_exclude_booking)
      and s.lesson_date = p_slot.lesson_date
      and s.start_time < p_slot.end_time
      and p_slot.start_time < s.end_time
  ) then
    raise exception 'OVERLAP';
  end if;
  select count(*)::integer into v_active
  from public.lesson_bookings b
  where b.slot_id = p_slot.id
    and b.status <> 'cancelled'
    and (p_exclude_booking is null or b.id <> p_exclude_booking);
  if v_active >= p_slot.capacity + p_slot.waitlist_capacity then
    raise exception 'FULL';
  end if;
end;
$$;

create or replace function public._lesson_queue_position(p_booking_id uuid)
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select count(*)::integer
  from public.lesson_bookings b
  join public.lesson_bookings me on me.id = p_booking_id
  where b.slot_id = me.slot_id
    and b.status <> 'cancelled'
    and b.queue_seq <= me.queue_seq;
$$;

-- ---------- public RPCs ----------
-- FCFS: slot row lock serializes bookers of one slot; member row lock serializes one
-- person's parallel clicks. Position = count of non-cancelled bookings with queue_seq <= mine.
create or replace function public.book_lesson_slot(p_slot_id uuid)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_slot public.lesson_slots;
  v_member public.members;
  v_settings public.lesson_booking_settings;
  v_booking_id uuid;
  v_position integer;
begin
  select * into v_slot from public.lesson_slots where id = p_slot_id for update;
  if v_slot.id is null then
    raise exception 'NO_SESSION';
  end if;
  v_member := _lesson_current_member(v_slot.club_id);
  perform 1 from public.members where id = v_member.id for update;
  v_settings := _lesson_settings(v_slot.club_id);

  perform _lesson_booking_checks(v_member, v_slot, v_settings, null);

  insert into public.lesson_bookings (club_id, slot_id, member_id, status, created_by, updated_by)
  values (v_slot.club_id, v_slot.id, v_member.id, 'booked', auth.uid(), auth.uid())
  returning id into v_booking_id;

  v_position := _lesson_queue_position(v_booking_id);
  return json_build_object(
    'booking_id', v_booking_id,
    'position', v_position,
    'capacity', v_slot.capacity,
    'waitlisted', v_position > v_slot.capacity
  );
end;
$$;

-- Move own booking to another slot. The mover gets a fresh queue_seq (back of the new queue).
create or replace function public.change_lesson_booking(p_booking_id uuid, p_slot_id uuid)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_booking public.lesson_bookings;
  v_from public.lesson_slots;
  v_slot public.lesson_slots;
  v_member public.members;
  v_settings public.lesson_booking_settings;
  v_position integer;
begin
  select * into v_slot from public.lesson_slots where id = p_slot_id for update;
  if v_slot.id is null then
    raise exception 'NO_SESSION';
  end if;
  v_member := _lesson_current_member(v_slot.club_id);
  perform 1 from public.members where id = v_member.id for update;

  select * into v_booking from public.lesson_bookings
  where id = p_booking_id and member_id = v_member.id and club_id = v_slot.club_id
  for update;
  if v_booking.id is null or v_booking.status <> 'booked' then
    raise exception 'NO_BOOKING';
  end if;
  if v_booking.slot_id = p_slot_id then
    raise exception 'DUPLICATE';
  end if;

  select * into v_from from public.lesson_slots where id = v_booking.slot_id;
  if not coalesce(v_from.allow_member_reschedule, true) then
    raise exception 'CHANGE_CLOSED';
  end if;
  if now() > _lesson_slot_start(v_from.lesson_date, v_from.start_time)
            - make_interval(hours => coalesce(v_from.reschedule_cutoff_hours, 12)) then
    raise exception 'CHANGE_CLOSED';
  end if;

  v_settings := _lesson_settings(v_slot.club_id);
  perform _lesson_booking_checks(v_member, v_slot, v_settings, v_booking.id);

  update public.lesson_bookings
  set slot_id = v_slot.id,
      queue_seq = default,
      attendance_note = null,
      checked_in_at = null,
      status = 'booked',
      updated_by = auth.uid()
  where id = v_booking.id;

  insert into public.lesson_booking_change_requests
    (booking_id, club_id, member_id, from_slot_id, to_slot_id, request_type, status,
     decided_at, decided_by, created_by, updated_by)
  values
    (v_booking.id, v_slot.club_id, v_member.id, v_booking.slot_id, v_slot.id, 'member_reschedule',
     'approved', now(), auth.uid(), auth.uid(), auth.uid());

  v_position := _lesson_queue_position(v_booking.id);
  return json_build_object(
    'booking_id', v_booking.id,
    'position', v_position,
    'capacity', v_slot.capacity,
    'waitlisted', v_position > v_slot.capacity
  );
end;
$$;

-- Cancel own booking. Confirmed seats respect cancel_cutoff_hours; waitlisted can always cancel.
create or replace function public.cancel_lesson_booking(p_booking_id uuid)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_booking public.lesson_bookings;
  v_slot public.lesson_slots;
  v_settings public.lesson_booking_settings;
  v_position integer;
begin
  select * into v_booking from public.lesson_bookings where id = p_booking_id for update;
  if v_booking.id is null then
    raise exception 'NO_BOOKING';
  end if;
  if not exists (
    select 1 from public.members m
    where m.id = v_booking.member_id and m.user_id = auth.uid()
  ) then
    raise exception 'NO_BOOKING';
  end if;
  if v_booking.status <> 'booked' then
    raise exception 'NO_BOOKING';
  end if;

  select * into v_slot from public.lesson_slots where id = v_booking.slot_id for update;
  if _lesson_slot_start(v_slot.lesson_date, v_slot.start_time) <= now() then
    raise exception 'STARTED';
  end if;

  v_settings := _lesson_settings(v_booking.club_id);
  v_position := _lesson_queue_position(v_booking.id);
  if v_position <= v_slot.capacity
     and now() > _lesson_slot_start(v_slot.lesson_date, v_slot.start_time)
                 - make_interval(hours => v_settings.cancel_cutoff_hours) then
    raise exception 'CANCEL_LOCKED';
  end if;

  update public.lesson_bookings
  set status = 'cancelled', updated_by = auth.uid()
  where id = v_booking.id;

  return json_build_object('booking_id', v_booking.id, 'slot_id', v_booking.slot_id, 'position', v_position);
end;
$$;

create or replace function public.ack_lesson_announcement(p_club_id uuid, p_version integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.members
  set lesson_announcement_ack_version = greatest(lesson_announcement_ack_version, p_version),
      updated_by = auth.uid()
  where user_id = auth.uid()
    and club_id = p_club_id
    and archived_at is null;
end;
$$;

-- Caller's active bookings with FCFS position. Members cannot see other bookings of a slot
-- through RLS, so the position is computed here.
create or replace function public.my_lesson_bookings()
returns table (
  booking_id uuid,
  slot_id uuid,
  queue_position integer,
  capacity integer,
  waitlist_capacity integer
)
language sql
stable
security definer
set search_path = public
as $$
  select
    b.id,
    b.slot_id,
    (
      select count(*)::integer from public.lesson_bookings o
      where o.slot_id = b.slot_id and o.status <> 'cancelled' and o.queue_seq <= b.queue_seq
    ),
    s.capacity,
    s.waitlist_capacity
  from public.lesson_bookings b
  join public.lesson_slots s on s.id = b.slot_id
  join public.members m on m.id = b.member_id
  where m.user_id = auth.uid()
    and b.status <> 'cancelled';
$$;

